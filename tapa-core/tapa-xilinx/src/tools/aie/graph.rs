//! The ADF sources of an [`AiePartition`]: `graph.cpp`, `kernels.h`, and
//! one kernel wrapper per kernel under `kernels/`.
//!
//! Every ADF port TAPA generates carries 32-bit words; `tapa/aie/tapa.h`
//! reads each element as its own type, so the graph never needs the user's
//! element types. A kernel wrapper includes the rewritten translation unit
//! that defines its task, with that task's guard defined, and calls the task
//! through `tapa::aie::invoke`, which builds each parameter from its ADF port.
//! Invoke-site constants are compiled into the wrapper.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use tapa_ir::port::sanitize_identifier_name;
use tapa_ir::{
    AieKernel, AieMemoryPort, AiePartition, AiePortKind, AieStream, AieStreamKind, ScalarBinding,
};

use crate::error::{Result, XilinxError};

/// The instance name of the generated graph, which XRT addresses it by. A
/// graph with a never-returning kernel is named apart, so the runtime knows
/// to run it forever and stop it rather than wait for it.
#[must_use]
const fn graph_instance(run_forever: bool) -> &'static str {
    if run_forever {
        "tapa_aie_forever"
    } else {
        "tapa_aie"
    }
}

/// Where each kernel's task is defined in the rewritten tree.
#[derive(Debug, Clone)]
pub struct KernelSource {
    /// The translation unit to include, relative to an include root.
    pub tu: String,
    /// The task's guard macros, defined before the include.
    pub defines: Vec<String>,
}

/// The simulator entry point of a graph built for x86sim or aiesim. It
/// reads the runtime parameters from `rtp.txt` in the directory the
/// simulator runs in: one line per [`runtime_parameters`] entry, in order,
/// holding the value's bits as a decimal 64-bit integer.
#[derive(Debug, Clone, Default)]
pub struct SimMain {
    /// Cycles a run-forever graph runs before the host ends it.
    pub cycles: u64,
}

/// The top scalar argument behind each runtime parameter, in the order a
/// simulation entry point reads them.
#[must_use]
pub fn runtime_parameters(partition: &AiePartition) -> Vec<String> {
    let mut args = Vec::new();
    for kernel in &partition.kernels {
        for port in &kernel.ports {
            if let AiePortKind::Scalar {
                value: ScalarBinding::Runtime(arg),
                ..
            } = &port.kind
            {
                args.push(arg.clone());
            }
        }
    }
    args
}

/// Inputs of [`render_graph`] beyond the partition.
#[derive(Debug, Clone, Default)]
pub struct GraphOptions {
    /// Task name → where its definition lives.
    pub sources: BTreeMap<String, KernelSource>,
    /// Top scalar argument → its index among the PL kernel's arguments,
    /// which each runtime parameter carrying it is named after.
    pub rtp_args: BTreeMap<String, u32>,
    /// The PL clock driving every PLIO, in MHz.
    pub plio_mhz: Option<f64>,
    /// Drive graph control through a PLIO and per-kernel packet controllers.
    pub pl_control: bool,
    /// The simulator `main` that writes the runtime parameters and runs the
    /// graph; without it, `main` only initializes and ends the graph.
    pub sim: Option<SimMain>,
}

/// The graph's runtime parameter for scalar `port` of `kernel`, carrying
/// the top scalar argument `arg` of the PL kernel. The leading index lets
/// the runtime find which argument value to write: `rtp_<arg>_<kernel>_<port>`.
#[must_use]
fn rtp_name(arg: u32, kernel: &str, port: &str) -> String {
    format!("rtp_{arg}_{kernel}_{}", sanitize_identifier_name(port))
}

fn rtp_arg(options: &GraphOptions, kernel: &str, arg: &str) -> Result<u32> {
    options.rtp_args.get(arg).copied().ok_or_else(|| {
        XilinxError::AieGraph(format!(
            "the AI Engine kernel `{kernel}` reads `{arg}`, which is not a scalar argument \
             of the PL kernel"
        ))
    })
}

/// File name → contents of every generated source, relative to the graph
/// directory.
pub fn render_graph(
    partition: &AiePartition,
    options: &GraphOptions,
) -> Result<BTreeMap<String, String>> {
    if options.pl_control
        && partition
            .streams
            .iter()
            .any(|stream| stream.name == "tapa_ctrl")
    {
        return Err(XilinxError::AieGraph(
            "`tapa_ctrl` is reserved for PL graph control".into(),
        ));
    }
    let mut files = BTreeMap::new();
    let mut decls = String::from(
        "// Generated by TAPA: the AI Engine kernels of this design.\n\
         #pragma once\n\n#include <adf.h>\n#include <tapa/aie/frame.h>\n\n",
    );
    let drain = drains(partition);
    for kernel in &partition.kernels {
        let signature = signature(kernel, &partition.streams, drain)?;
        let _ = writeln!(decls, "{signature};");
        let source = options.sources.get(&kernel.task).ok_or_else(|| {
            XilinxError::AieGraph(format!(
                "no translation unit defines the AI Engine task `{}`",
                kernel.task
            ))
        })?;
        files.insert(
            format!("kernels/{}.cc", kernel.name),
            wrapper(kernel, &partition.streams, source, &signature, drain)?,
        );
    }
    files.insert("kernels.h".to_string(), decls);
    files.insert("graph.cpp".to_string(), graph(partition, options)?);
    Ok(files)
}

/// The ADF scalar type a runtime parameter of `ctype` travels as.
fn rtp_type(ctype: &str, width: u32) -> Result<&'static str> {
    let unsigned = ctype.contains("unsigned")
        || ctype.trim_start_matches("std::").starts_with("uint")
        || ctype == "bool"
        || ctype.contains("size_t");
    let ty = match (ctype, width) {
        ("float", 32) => "float",
        (_, 8 | 1) if unsigned => "uint8",
        (_, 8) => "int8",
        (_, 16) if unsigned => "unsigned short",
        (_, 16) => "short",
        (_, 32) if unsigned => "unsigned int",
        (_, 32) => "int",
        (_, 64) if unsigned => "uint64",
        (_, 64) if !ctype.contains("double") => "int64",
        _ => {
            return Err(XilinxError::AieGraph(format!(
                "a scalar of type `{ctype}` ({width} bits) cannot reach the AI Engine; \
                 use a 8-, 16-, 32- or 64-bit integer or a float"
            )))
        }
    };
    Ok(ty)
}

/// ADF's default kernel stack, which holds the kernel's own frame and
/// spills; the task's local variables come on top of it.
const DEFAULT_STACK_BYTES: u32 = 1024;

/// The stack a kernel whose task has `locals` bytes of local variables
/// needs, kept 16-byte aligned.
/// The ADF ports of an `async_mmap` port, in parameter order: the
/// parameter's name suffix, its stream, and whether the kernel reads it.
fn memory_channels(memory: &AieMemoryPort) -> Vec<(&'static str, usize, bool)> {
    let mut channels = Vec::new();
    if let Some(reads) = &memory.reads {
        channels.push(("read_addr", reads.requests, false));
        channels.push(("read_data", reads.data, true));
    }
    if let Some(writes) = &memory.writes {
        channels.push(("write", writes.requests, false));
        if let Some(responses) = writes.responses {
            channels.push(("write_resp", responses, true));
        }
    }
    channels
}

/// The `tapa::aie::memory{read_addr, read_data, write_addr, write_data,
/// write_resp}` of an `async_mmap` port: a write request and its data share
/// one port, and a channel the body never names is null.
fn memory_arg(name: &str, memory: &AieMemoryPort) -> String {
    let port = |present: bool, suffix: &str| {
        if present {
            format!("{name}_{suffix}")
        } else {
            "nullptr".to_string()
        }
    };
    let reads = memory.reads.is_some();
    let writes = memory.writes.is_some();
    let responses = memory
        .writes
        .as_ref()
        .is_some_and(|w| w.responses.is_some());
    format!(
        "tapa::aie::memory{{{}, {}, {}, {}, {}}}",
        port(reads, "read_addr"),
        port(reads, "read_data"),
        port(writes, "write"),
        port(writes, "write"),
        port(responses, "write_resp")
    )
}

const fn stack_size(locals: u32) -> u32 {
    DEFAULT_STACK_BYTES
        .saturating_add(locals)
        .next_multiple_of(16)
}

/// The NoC burst of every GMIO, the longest there is.
const GMIO_BURST_BYTES: u32 = 256;

/// The throughput every GMIO asks of the NoC, in MB/s.
const GMIO_MBPS: u32 = 1000;

/// The kernel's frame ports that write a GMIO: each parameter's name and
/// its stream. The kernel reports the frames it released on each through
/// an `inout` runtime parameter, `frames_<GMIO>`, so the host knows when a
/// run's last frame has arrived.
fn counted_outputs(kernel: &AieKernel, streams: &[AieStream]) -> Result<Vec<(String, usize)>> {
    let mut counted = Vec::new();
    for port in &kernel.ports {
        let AiePortKind::Streams {
            input: false,
            plural,
            streams: channels,
            ..
        } = &port.kind
        else {
            continue;
        };
        for &stream in channels {
            if !matches!(streams[stream].kind, AieStreamKind::Gmio { .. }) {
                continue;
            }
            if *plural {
                return Err(XilinxError::AieGraph(format!(
                    "the port `{}` of the AI Engine kernel `{}` writes the top's stream \
                     argument `{}` from a channel of an `ostreams` port; bind it to a single \
                     frame port",
                    port.name, kernel.name, streams[stream].fifo
                )));
            }
            counted.push((sanitize_identifier_name(&port.name), stream));
        }
    }
    Ok(counted)
}

/// Whether the graph writes a GMIO. Each run then leaves a transfer posted
/// on every output GMIO, waiting for a frame that may come next, and the
/// host retires it with a drain run: every kernel takes a `drain` runtime
/// parameter (`drain_<kernel>`) and, when it is set, skips its task and
/// releases one frame on each GMIO it writes.
fn drains(partition: &AiePartition) -> bool {
    partition
        .streams
        .iter()
        .any(|stream| matches!(stream.kind, AieStreamKind::Gmio { input: false }))
}

/// One ADF kernel parameter per stream channel, frame or runtime scalar,
/// then the drain flag ([`drains`]), then one frame count per GMIO the
/// kernel writes.
fn signature(kernel: &AieKernel, streams: &[AieStream], drain: bool) -> Result<String> {
    let mut params = Vec::new();
    for port in &kernel.ports {
        let name = sanitize_identifier_name(&port.name);
        match &port.kind {
            AiePortKind::Streams {
                input,
                streams,
                plural,
                words,
                frame,
            } => {
                let dir = if *input { "input" } else { "output" };
                for (i, _) in streams.iter().enumerate() {
                    let param = if *plural {
                        format!("{name}_{i}")
                    } else {
                        name.clone()
                    };
                    params.push(match frame {
                        Some(n) => format!("tapa::aie::{dir}_frame<int32, {}>& {param}", n * words),
                        None => format!("{dir}_stream<int32>* {param}"),
                    });
                }
            }
            AiePortKind::Scalar {
                ctype,
                width,
                value: ScalarBinding::Runtime(_),
            } => params.push(format!("{} {name}", rtp_type(ctype, *width)?)),
            AiePortKind::Scalar { .. } => {}
            AiePortKind::Memory(memory) => {
                for (channel, _, input) in memory_channels(memory) {
                    let dir = if input { "input" } else { "output" };
                    params.push(format!("{dir}_stream<int32>* {name}_{channel}"));
                }
            }
        }
    }
    if drain {
        params.push("int32 tapa_drain".to_string());
    }
    for (param, _) in counted_outputs(kernel, streams)? {
        params.push(format!("int32 & tapa_frames_{param}"));
    }
    Ok(format!(
        "void tapa_aie_{}({})",
        kernel.name,
        params.join(", ")
    ))
}

fn wrapper(
    kernel: &AieKernel,
    streams: &[AieStream],
    source: &KernelSource,
    signature: &str,
    drain: bool,
) -> Result<String> {
    let counted = counted_outputs(kernel, streams)?;
    let mut args = Vec::new();
    for port in &kernel.ports {
        let name = sanitize_identifier_name(&port.name);
        match &port.kind {
            AiePortKind::Streams {
                plural: true,
                streams,
                ..
            } => {
                let channels: Vec<String> =
                    (0..streams.len()).map(|i| format!("{name}_{i}")).collect();
                args.push(format!("tapa::aie::pack({})", channels.join(", ")));
            }
            AiePortKind::Scalar {
                value: ScalarBinding::Constant(value),
                ..
            } => args.push(format!("tapa::aie::bits{{{:#x}ULL}}", value.value)),
            AiePortKind::Memory(memory) => args.push(memory_arg(&name, memory)),
            AiePortKind::Streams { .. } if counted.iter().any(|(param, _)| *param == name) => {
                args.push(format!("tapa::aie::count({name}, frames_{name})"));
            }
            AiePortKind::Streams { .. } | AiePortKind::Scalar { .. } => args.push(name),
        }
    }
    let mut out = format!(
        "// Generated by TAPA: AI Engine kernel `{}` of task `{}`.\n",
        kernel.name, kernel.task
    );
    for define in &source.defines {
        let _ = writeln!(out, "#define {define}");
    }
    if kernel.ordered {
        let _ = writeln!(out, "#define TAPA_AIE_ORDERED_STREAMS");
    }
    let _ = write!(out, "#include \"{}\"\n\n{signature} {{\n", source.tu);
    if drain {
        out.push_str("  if (tapa_drain != 0) {\n");
        for (param, _) in &counted {
            let _ = writeln!(out, "    {param}.acquire();\n    {param}.release();");
        }
        out.push_str("    return;\n  }\n");
    }
    for (param, _) in &counted {
        let _ = writeln!(out, "  int32 frames_{param} = 0;");
    }
    let _ = writeln!(
        out,
        "  tapa::aie::invoke({}, {});",
        kernel.call,
        args.join(", ")
    );
    for (param, _) in &counted {
        let _ = writeln!(out, "  tapa_frames_{param} = frames_{param};");
    }
    out.push_str("}\n");
    Ok(out)
}

/// One end of a stream connection, as ADF spells it.
#[derive(Debug, Clone)]
struct End {
    port: String,
    frame: bool,
}

/// `graph.cpp` as it accumulates: class members, constructor body, and the
/// two ends of every stream by stream index.
#[derive(Default)]
struct GraphText {
    members: String,
    body: String,
    producers: BTreeMap<usize, End>,
    consumers: BTreeMap<usize, End>,
}

impl GraphText {
    fn kernel(
        &mut self,
        kernel: &AieKernel,
        streams: &[AieStream],
        options: &GraphOptions,
        drain: bool,
    ) -> Result<()> {
        let k = format!("k_{}", kernel.name);
        let _ = writeln!(self.members, "  adf::kernel {k};");
        let _ = writeln!(
            self.body,
            "    {k} = adf::kernel::create(tapa_aie_{name});\n    \
             adf::source({k}) = \"kernels/{name}.cc\";\n    \
             adf::runtime<adf::ratio>({k}) = 0.9;",
            name = kernel.name
        );
        if let Some((col, row)) = kernel.location {
            let _ = writeln!(
                self.body,
                "    adf::location<adf::kernel>({k}) = adf::tile({col}, {row});"
            );
        }
        if let Some(locals) = kernel.stack_bytes {
            let _ = writeln!(
                self.body,
                "    adf::stack_size({k}) = {};",
                stack_size(locals)
            );
        }
        // ADF numbers a kernel's inputs (streams, buffers, runtime
        // parameters) and outputs separately, in parameter order.
        let (mut inputs, mut outputs) = (0, 0);
        for port in &kernel.ports {
            match &port.kind {
                AiePortKind::Streams {
                    input,
                    streams,
                    frame,
                    ..
                } => {
                    for stream in streams {
                        let (table, dir, index) = if *input {
                            (&mut self.consumers, "in", &mut inputs)
                        } else {
                            (&mut self.producers, "out", &mut outputs)
                        };
                        table.insert(
                            *stream,
                            End {
                                port: format!("{k}.{dir}[{index}]"),
                                frame: frame.is_some(),
                            },
                        );
                        *index += 1;
                    }
                }
                AiePortKind::Scalar {
                    value: ScalarBinding::Runtime(arg),
                    ..
                } => {
                    let rtp = rtp_name(
                        rtp_arg(options, &kernel.name, arg)?,
                        &kernel.name,
                        &port.name,
                    );
                    let _ = writeln!(self.members, "  adf::port<adf::input> {rtp};");
                    let _ = writeln!(
                        self.body,
                        "    adf::connect<adf::parameter>({rtp}, adf::async({k}.in[{inputs}]));"
                    );
                    if options.pl_control {
                        let _ = writeln!(
                            self.body,
                            "    adf::single_buffer({k}.in[{inputs}]);\n    \
                             adf::location<adf::buffer>({k}.in[{inputs}]) = \
                             adf::location<adf::kernel>({k});"
                        );
                    }
                    inputs += 1;
                }
                AiePortKind::Scalar { .. } => {}
                AiePortKind::Memory(memory) => {
                    for (_, stream, input) in memory_channels(memory) {
                        let (table, dir, index) = if input {
                            (&mut self.consumers, "in", &mut inputs)
                        } else {
                            (&mut self.producers, "out", &mut outputs)
                        };
                        table.insert(
                            stream,
                            End {
                                port: format!("{k}.{dir}[{index}]"),
                                frame: false,
                            },
                        );
                        *index += 1;
                    }
                }
            }
        }
        self.gmio_parameters(kernel, streams, drain, inputs)
    }

    /// The runtime parameters a graph writing a GMIO adds after a kernel's
    /// own: its drain flag, the next input, and the frame count of each
    /// GMIO it writes, read once the kernel has returned, so asynchronously.
    fn gmio_parameters(
        &mut self,
        kernel: &AieKernel,
        streams: &[AieStream],
        drain: bool,
        input: usize,
    ) -> Result<()> {
        let k = format!("k_{}", kernel.name);
        if drain {
            let rtp = format!("drain_{}", kernel.name);
            let _ = writeln!(self.members, "  adf::port<adf::input> {rtp};");
            let _ = writeln!(
                self.body,
                "    adf::connect<adf::parameter>({rtp}, adf::async({k}.in[{input}]));"
            );
        }
        for (inout, (_, stream)) in counted_outputs(kernel, streams)?.into_iter().enumerate() {
            let rtp = format!("frames_{}", streams[stream].name);
            let _ = writeln!(self.members, "  adf::port<adf::inout> {rtp};");
            let _ = writeln!(
                self.body,
                "    adf::connect<adf::parameter>(adf::async({k}.inout[{inout}]), {rtp});"
            );
        }
        Ok(())
    }

    fn plio(&mut self, index: usize, stream: &AieStream, input: bool, width: u32, freq: &str) {
        let p = format!("p_{}", stream.name);
        let (class, end, table) = if input {
            ("input_plio", "out", &mut self.producers)
        } else {
            ("output_plio", "in", &mut self.consumers)
        };
        let _ = writeln!(self.members, "  adf::{class} {p};");
        let _ = writeln!(
            self.body,
            "    {p} = adf::{class}::create(\"{name}\", adf::plio_{width}_bits, \
             \"data/{name}.txt\"{freq});",
            name = stream.name
        );
        table.insert(
            index,
            End {
                port: format!("{p}.{end}[0]"),
                frame: false,
            },
        );
    }

    fn gmio(&mut self, index: usize, stream: &AieStream, input: bool) {
        let g = format!("g_{}", stream.name);
        let (class, end, table) = if input {
            ("input_gmio", "out", &mut self.producers)
        } else {
            ("output_gmio", "in", &mut self.consumers)
        };
        let _ = writeln!(self.members, "  adf::{class} {g};");
        let _ = writeln!(
            self.body,
            "    {g} = adf::{class}::create(\"{name}\", {GMIO_BURST_BYTES}, {GMIO_MBPS});",
            name = stream.name
        );
        table.insert(
            index,
            End {
                port: format!("{g}.{end}[0]"),
                frame: true,
            },
        );
    }

    fn pl_control(&mut self, kernels: &[AieKernel], freq: &str) {
        let _ = writeln!(self.members, "  adf::input_plio p_tapa_ctrl;");
        let _ = writeln!(
            self.body,
            "    p_tapa_ctrl = adf::input_plio::create(\"tapa_ctrl\", \
             adf::plio_32_bits, \"data/tapa_ctrl.txt\"{freq});"
        );
        for kernel in kernels {
            let control = format!("control_{}", kernel.name);
            let _ = writeln!(self.members, "  adf::pktcontrol {control};");
            let _ = writeln!(
                self.body,
                "    {control} = adf::pktcontrol::create();\n    \
                 adf::connect<adf::pktstream, adf::pktstream> n_{control}\
                 (p_tapa_ctrl.out[0], {control}.in[0]);\n    \
                 adf::location<adf::interconnect>({control}) = \
                 adf::location<adf::kernel>(k_{});",
                kernel.name
            );
        }
    }

    fn connect(&mut self, index: usize, stream: &AieStream) -> Result<()> {
        let (Some(src), Some(dst)) = (self.producers.get(&index), self.consumers.get(&index))
        else {
            return Err(XilinxError::AieGraph(format!(
                "AI Engine stream `{}` lacks a producer or a consumer",
                stream.fifo
            )));
        };
        let net = format!("n_{}", stream.name);
        let frame = src.frame || dst.frame;
        let kind = if frame { "" } else { "<adf::stream>" };
        let _ = writeln!(
            self.body,
            "    adf::connect{kind} {net}({}, {});",
            src.port, dst.port
        );
        if let AieStreamKind::Net { depth_words } = stream.kind {
            if !frame && depth_words > 0 {
                let _ = writeln!(self.body, "    adf::fifo_depth({net}) = {depth_words};");
            }
        }
        Ok(())
    }
}

fn graph(partition: &AiePartition, options: &GraphOptions) -> Result<String> {
    let mut text = GraphText::default();
    for kernel in &partition.kernels {
        text.kernel(kernel, &partition.streams, options, drains(partition))?;
    }
    let freq = options
        .plio_mhz
        .map(|mhz| format!(", {mhz}"))
        .unwrap_or_default();
    if options.pl_control {
        text.pl_control(&partition.kernels, &freq);
    }
    for (index, stream) in partition.streams.iter().enumerate() {
        match stream.kind {
            AieStreamKind::Plio { input, width } => text.plio(index, stream, input, width, &freq),
            AieStreamKind::Gmio { input } => text.gmio(index, stream, input),
            AieStreamKind::Net { .. } => {}
        }
    }
    for (index, stream) in partition.streams.iter().enumerate() {
        text.connect(index, stream)?;
    }
    let graph = graph_instance(partition.run_forever);
    let mut out = format!(
        "// Generated by TAPA: the AI Engine graph of this design.\n\
         #include <adf.h>\n\n#include \"kernels.h\"\n\n\
         class TapaAieGraph : public adf::graph {{\n public:\n{members}\n  \
         TapaAieGraph() {{\n{body}  }}\n}};\n\nTapaAieGraph {graph};\n",
        members = text.members,
        body = text.body,
    );
    // `aiecompiler --target=hw` builds a simulation model of the PS side
    // too, which needs an entry point even when only `libadf.a` is wanted.
    match &options.sim {
        Some(sim) => out.push_str(&sim_main(partition, options, sim)?),
        None => {
            let _ = write!(
                out,
                "\n#if defined(__AIESIM__) || defined(__X86SIM__)\n\
                 // A simulation package builds the graph with its own entry point.\n\
                 int main() {{\n  {graph}.init();\n  {graph}.end();\n  \
                 return 0;\n}}\n#endif\n"
            );
        }
    }
    Ok(out)
}

/// What a simulator entry point needs to move GMIO frames. A stream file
/// holds 32-bit words with `TLAST` lines between frames, as frt writes and
/// reads a PLIO's. Live, x86sim lets host threads post and wait on GMIOs,
/// so each frame moves as it arrives; aiesim does not, so a replay posts
/// every input frame, and room for every output frame software simulation
/// wrote, before the graph runs.
const GMIO_SIM_HELPERS: &str = r#"
namespace {

// The next 32-bit word of a stream file, past its `TLAST` markers.
bool tapa_word(std::istream& in, int32_t& word) {
  std::string token;
  while (in >> token) {
    if (token != "TLAST") {
      word = static_cast<int32_t>(std::stoll(token));
      return true;
    }
  }
  return false;
}

// Appends one frame to a stream file.
void tapa_put(std::ostream& out, const int32_t* frame, size_t words) {
  for (size_t i = 0; i < words; ++i) out << frame[i] << '\n';
  out.flush();
}

#if defined(__X86SIM__)
// Posts each frame of `path` as it arrives, one transfer at a time.
void tapa_feed(adf::input_gmio& gmio, const char* path, size_t words) {
  std::ifstream in(path);
  auto* frame = static_cast<int32_t*>(adf::GMIO::malloc(words * 4));
  for (;;) {
    for (size_t i = 0; i < words; ++i) {
      if (!tapa_word(in, frame[i])) return;
    }
    gmio.gm2aie_nb(frame, words * 4);
    gmio.wait();
  }
}

// Appends each frame `gmio` delivers to `path`, one transfer at a time.
void tapa_drain(adf::output_gmio& gmio, const char* path, size_t words,
                std::atomic<int>& done) {
  std::ofstream out(path);
  auto* frame = static_cast<int32_t*>(adf::GMIO::malloc(words * 4));
  for (;;) {
    gmio.aie2gm_nb(frame, words * 4);
    gmio.wait();
    tapa_put(out, frame, words);
    done.fetch_add(1);
  }
}
#else
// Posts every frame of `path` in one transfer.
void tapa_feed(adf::input_gmio& gmio, const char* path) {
  std::ifstream in(path);
  std::vector<int32_t> words;
  for (int32_t word = 0; tapa_word(in, word);) words.push_back(word);
  if (words.empty()) return;
  void* buf = adf::GMIO::malloc(words.size() * 4);
  std::memcpy(buf, words.data(), words.size() * 4);
  gmio.gm2aie_nb(buf, words.size() * 4);
}
#endif

}  // namespace
"#;

/// The file of a replay's expected output frame counts, one line per
/// output GMIO in stream order (frt writes it).
const GMIO_FRAMES_FILE: &str = "frames.txt";

fn sim_main(partition: &AiePartition, options: &GraphOptions, sim: &SimMain) -> Result<String> {
    let graph = graph_instance(partition.run_forever);
    let gmios: Vec<(&AieStream, bool)> = partition
        .streams
        .iter()
        .filter_map(|stream| match stream.kind {
            AieStreamKind::Gmio { input } => Some((stream, input)),
            _ => None,
        })
        .collect();
    let mut out = String::from(
        "\n#if defined(__AIESIM__) || defined(__X86SIM__)\n#include <cstdint>\n\
         #include <cstring>\n#include <fstream>\n",
    );
    if !gmios.is_empty() {
        out.push_str(
            "#include <atomic>\n#include <cstdio>\n#include <cstdlib>\n#include <string>\n\
             #include <thread>\n#include <vector>\n",
        );
        out.push_str(GMIO_SIM_HELPERS);
    }
    let _ = write!(
        out,
        "\nint main() {{\n  {graph}.init();\n  std::ifstream rtp(\"rtp.txt\");\n"
    );
    // A simulation runs once, so it never drains.
    if drains(partition) {
        for kernel in &partition.kernels {
            let _ = writeln!(out, "  {graph}.update({graph}.drain_{}, 0);", kernel.name);
        }
    }
    for kernel in &partition.kernels {
        for port in &kernel.ports {
            if let AiePortKind::Scalar {
                ctype,
                width,
                value: ScalarBinding::Runtime(arg),
            } = &port.kind
            {
                let _ = writeln!(
                    out,
                    "  {{\n    uint64_t bits = 0;\n    rtp >> bits;\n    {} value;\n    \
                     std::memcpy(&value, &bits, sizeof value);\n    \
                     {graph}.update({graph}.{}, value);\n  }}",
                    rtp_type(ctype, *width)?,
                    rtp_name(
                        rtp_arg(options, &kernel.name, arg)?,
                        &kernel.name,
                        &port.name
                    ),
                );
            }
        }
    }
    // ADF's `run(0)` runs zero iterations; `run()` runs until `end()`.
    if partition.run_forever {
        let _ = writeln!(out, "  {graph}.run();\n  {graph}.wait({});", sim.cycles);
    } else if gmios.is_empty() {
        let _ = writeln!(out, "  {graph}.run(1);");
    } else {
        out.push_str(&gmio_run(graph, &gmios));
    }
    let _ = writeln!(out, "  {graph}.end();\n  return 0;\n}}\n#endif");
    Ok(out)
}

/// One run of a graph with GMIOs: live on x86sim, a replay on aiesim. Each
/// waits until every output has the frames the kernels report writing.
fn gmio_run(graph: &str, gmios: &[(&AieStream, bool)]) -> String {
    let words = |stream: &AieStream| stream.frame.unwrap_or(1) * stream.words;
    let mut live = String::new();
    let mut replay = format!("  std::ifstream expected(\"{GMIO_FRAMES_FILE}\");\n");
    for (stream, input) in gmios {
        let (name, words) = (&stream.name, words(stream));
        if *input {
            let _ = writeln!(
                live,
                "  std::thread(tapa_feed, std::ref({graph}.g_{name}), \"data/{name}.txt\", \
                 size_t{{{words}}}).detach();"
            );
            let _ = writeln!(
                replay,
                "  tapa_feed({graph}.g_{name}, \"data/{name}.txt\");"
            );
        } else {
            let _ = writeln!(
                live,
                "  std::atomic<int> done_{name}{{0}};\n  \
                 std::thread(tapa_drain, std::ref({graph}.g_{name}), \"data/{name}.txt\", \
                 size_t{{{words}}}, std::ref(done_{name})).detach();"
            );
            let _ = writeln!(
                replay,
                "  long expected_{name} = 0;\n  expected >> expected_{name};\n  \
                 int32_t* out_{name} = nullptr;\n  \
                 if (expected_{name} != 0) {{\n    \
                 out_{name} = static_cast<int32_t*>(\n        \
                 adf::GMIO::malloc(expected_{name} * {bytes}));\n    \
                 {graph}.g_{name}.aie2gm_nb(out_{name}, expected_{name} * {bytes});\n  }}",
                bytes = words * 4
            );
        }
    }
    let run = format!("  {graph}.run(1);\n  {graph}.wait();\n");
    live.push_str(&run);
    replay.push_str(&run);
    for (stream, input) in gmios {
        if *input {
            continue;
        }
        let (name, words) = (&stream.name, words(stream));
        let _ = writeln!(
            live,
            "  {{\n    int32 frames = 0;\n    {graph}.read({graph}.frames_{name}, frames);\n    \
             while (done_{name}.load() < frames) std::this_thread::yield();\n  }}"
        );
        let _ = writeln!(
            replay,
            "  {{\n    int32 frames = 0;\n    {graph}.read({graph}.frames_{name}, frames);\n    \
             if (frames != expected_{name}) {{\n      \
             std::printf(\"TAPA: the graph wrote %d frame(s) to `{name}`; software \
             simulation wrote %ld\\n\", (int)frames, expected_{name});\n      \
             std::fflush(stdout);\n      std::_Exit(1);\n    }}\n    \
             if (expected_{name} != 0) {graph}.g_{name}.wait();\n    \
             std::ofstream out(\"data/{name}.txt\");\n    \
             for (long f = 0; f < expected_{name}; ++f)\n      \
             tapa_put(out, out_{name} + f * {words}, {words});\n  }}"
        );
    }
    // Feeds and drains still wait on transfers no run will fill.
    live.push_str("  std::fflush(nullptr);\n  std::_Exit(0);\n");
    format!("#if defined(__X86SIM__)\n{live}#else\n{replay}#endif\n")
}

