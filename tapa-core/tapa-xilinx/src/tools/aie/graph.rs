//! The ADF sources of an [`AiePartition`]: `graph.cpp`, `kernels.h`, and
//! one kernel wrapper per kernel under `kernels/`.
//!
//! Every ADF port TAPA generates carries 32-bit words; `tapa/aie/tapa.h`
//! reads each element as its own type, so the graph never needs the user's
//! element types. A kernel wrapper includes the rewritten translation unit
//! that defines its task, with that task's guard defined, and calls the task
//! through `tapa::aie::invoke`, which builds each parameter from its ADF port.
//! Invoke-site constants are compiled into the wrapper.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use tapa_ir::port::sanitize_identifier_name;
use tapa_ir::{AieKernel, AiePartition, AiePortKind, AieStream, AieStreamKind, ScalarBinding};

use crate::error::{Result, XilinxError};

/// The instance name of the generated graph, which XRT addresses it by. A
/// graph with a never-returning kernel is named apart, so the runtime knows
/// to run it forever and stop it rather than wait for it.
#[must_use]
pub const fn graph_instance(run_forever: bool) -> &'static str {
    if run_forever {
        "tapa_aie_forever"
    } else {
        "tapa_aie"
    }
}

/// Where each kernel's task is defined in the rewritten tree.
#[derive(Debug, Clone)]
pub struct KernelSource {
    /// The translation unit to include, relative to an include root.
    pub tu: String,
    /// The task's guard macros, defined before the include.
    pub defines: Vec<String>,
}

/// The simulator entry point of a graph built for x86sim or aiesim.
#[derive(Debug, Clone, Default)]
pub struct SimMain {
    /// Top scalar argument → its value, as a C++ literal.
    pub args: BTreeMap<String, String>,
    /// Cycles a run-forever graph runs before the host ends it.
    pub cycles: u64,
}

/// Inputs of [`render_graph`] beyond the partition.
#[derive(Debug, Clone, Default)]
pub struct GraphOptions {
    /// Task name → where its definition lives.
    pub sources: BTreeMap<String, KernelSource>,
    /// Top scalar argument → its index among the PL kernel's arguments,
    /// which each runtime parameter carrying it is named after.
    pub rtp_args: BTreeMap<String, u32>,
    /// The PL clock driving every PLIO, in MHz.
    pub plio_mhz: Option<f64>,
    /// The simulator `main` that writes the runtime parameters and runs the
    /// graph; without it, `main` only initializes and ends the graph.
    pub sim: Option<SimMain>,
}

/// The graph's runtime parameter for scalar `port` of `kernel`, carrying
/// the top scalar argument `arg` of the PL kernel. The leading index lets
/// the runtime find which argument value to write: `rtp_<arg>_<kernel>_<port>`.
#[must_use]
pub fn rtp_name(arg: u32, kernel: &str, port: &str) -> String {
    format!("rtp_{arg}_{kernel}_{}", sanitize_identifier_name(port))
}

fn rtp_arg(options: &GraphOptions, kernel: &str, arg: &str) -> Result<u32> {
    options.rtp_args.get(arg).copied().ok_or_else(|| {
        XilinxError::AieGraph(format!(
            "the AI Engine kernel `{kernel}` reads `{arg}`, which is not a scalar argument \
             of the PL kernel"
        ))
    })
}

/// File name → contents of every generated source, relative to the graph
/// directory.
pub fn render_graph(
    partition: &AiePartition,
    options: &GraphOptions,
) -> Result<BTreeMap<String, String>> {
    let mut files = BTreeMap::new();
    let mut decls = String::from(
        "// Generated by TAPA: the AI Engine kernels of this design.\n\
         #pragma once\n\n#include <adf.h>\n#include <tapa/aie/frame.h>\n\n",
    );
    for kernel in &partition.kernels {
        let signature = signature(kernel)?;
        let _ = writeln!(decls, "{signature};");
        let source = options.sources.get(&kernel.task).ok_or_else(|| {
            XilinxError::AieGraph(format!(
                "no translation unit defines the AI Engine task `{}`",
                kernel.task
            ))
        })?;
        files.insert(
            format!("kernels/{}.cc", kernel.name),
            wrapper(kernel, source, &signature),
        );
    }
    files.insert("kernels.h".to_string(), decls);
    files.insert("graph.cpp".to_string(), graph(partition, options)?);
    Ok(files)
}

/// The ADF scalar type a runtime parameter of `ctype` travels as.
fn rtp_type(ctype: &str, width: u32) -> Result<&'static str> {
    let unsigned = ctype.contains("unsigned")
        || ctype.trim_start_matches("std::").starts_with("uint")
        || ctype == "bool"
        || ctype.contains("size_t");
    let ty = match (ctype, width) {
        ("float", 32) => "float",
        (_, 8 | 1) if unsigned => "uint8",
        (_, 8) => "int8",
        (_, 16) if unsigned => "unsigned short",
        (_, 16) => "short",
        (_, 32) if unsigned => "unsigned int",
        (_, 32) => "int",
        (_, 64) if unsigned => "uint64",
        (_, 64) if !ctype.contains("double") => "int64",
        _ => {
            return Err(XilinxError::AieGraph(format!(
                "a scalar of type `{ctype}` ({width} bits) cannot reach the AI Engine; \
                 use a 8-, 16-, 32- or 64-bit integer or a float"
            )))
        }
    };
    Ok(ty)
}

/// ADF's default kernel stack, which holds the kernel's own frame and
/// spills; the task's local variables come on top of it.
const DEFAULT_STACK_BYTES: u32 = 1024;

/// The stack a kernel whose task has `locals` bytes of local variables
/// needs, kept 16-byte aligned.
const fn stack_size(locals: u32) -> u32 {
    DEFAULT_STACK_BYTES
        .saturating_add(locals)
        .next_multiple_of(16)
}

/// One ADF kernel parameter per stream channel, frame or runtime scalar.
fn signature(kernel: &AieKernel) -> Result<String> {
    let mut params = Vec::new();
    for port in &kernel.ports {
        let name = sanitize_identifier_name(&port.name);
        match &port.kind {
            AiePortKind::Streams {
                input,
                streams,
                plural,
                words,
                frame,
            } => {
                let dir = if *input { "input" } else { "output" };
                for (i, _) in streams.iter().enumerate() {
                    let param = if *plural {
                        format!("{name}_{i}")
                    } else {
                        name.clone()
                    };
                    params.push(match frame {
                        Some(n) => format!("tapa::aie::{dir}_frame<int32, {}>& {param}", n * words),
                        None => format!("{dir}_stream<int32>* {param}"),
                    });
                }
            }
            AiePortKind::Scalar {
                ctype,
                width,
                value: ScalarBinding::Runtime(_),
            } => params.push(format!("{} {name}", rtp_type(ctype, *width)?)),
            AiePortKind::Scalar { .. } => {}
        }
    }
    Ok(format!(
        "void tapa_aie_{}({})",
        kernel.name,
        params.join(", ")
    ))
}

fn wrapper(kernel: &AieKernel, source: &KernelSource, signature: &str) -> String {
    let mut args = Vec::new();
    for port in &kernel.ports {
        let name = sanitize_identifier_name(&port.name);
        match &port.kind {
            AiePortKind::Streams {
                plural: true,
                streams,
                ..
            } => {
                let channels: Vec<String> =
                    (0..streams.len()).map(|i| format!("{name}_{i}")).collect();
                args.push(format!("tapa::aie::pack({})", channels.join(", ")));
            }
            AiePortKind::Scalar {
                value: ScalarBinding::Constant(value),
                ..
            } => args.push(format!("tapa::aie::bits{{{:#x}ULL}}", value.value)),
            AiePortKind::Streams { .. } | AiePortKind::Scalar { .. } => args.push(name),
        }
    }
    let mut out = format!(
        "// Generated by TAPA: AI Engine kernel `{}` of task `{}`.\n",
        kernel.name, kernel.task
    );
    for define in &source.defines {
        let _ = writeln!(out, "#define {define}");
    }
    if kernel.ordered {
        let _ = writeln!(out, "#define TAPA_AIE_ORDERED_STREAMS");
    }
    let _ = write!(
        out,
        "#include \"{}\"\n\n{signature} {{\n  tapa::aie::invoke({}, {});\n}}\n",
        source.tu,
        kernel.call,
        args.join(", ")
    );
    out
}

/// One end of a stream connection, as ADF spells it.
#[derive(Debug, Clone)]
struct End {
    port: String,
    frame: bool,
}

/// `graph.cpp` as it accumulates: class members, constructor body, and the
/// two ends of every stream by stream index.
#[derive(Default)]
struct GraphText {
    members: String,
    body: String,
    producers: BTreeMap<usize, End>,
    consumers: BTreeMap<usize, End>,
}

impl GraphText {
    fn kernel(&mut self, kernel: &AieKernel, options: &GraphOptions) -> Result<()> {
        let k = format!("k_{}", kernel.name);
        let _ = writeln!(self.members, "  adf::kernel {k};");
        let _ = writeln!(
            self.body,
            "    {k} = adf::kernel::create(tapa_aie_{name});\n    \
             adf::source({k}) = \"kernels/{name}.cc\";\n    \
             adf::runtime<adf::ratio>({k}) = 0.9;",
            name = kernel.name
        );
        if let Some((col, row)) = kernel.location {
            let _ = writeln!(
                self.body,
                "    adf::location<adf::kernel>({k}) = adf::tile({col}, {row});"
            );
        }
        if let Some(locals) = kernel.stack_bytes {
            let _ = writeln!(
                self.body,
                "    adf::stack_size({k}) = {};",
                stack_size(locals)
            );
        }
        // ADF numbers a kernel's inputs (streams, buffers, runtime
        // parameters) and outputs separately, in parameter order.
        let (mut inputs, mut outputs) = (0, 0);
        for port in &kernel.ports {
            match &port.kind {
                AiePortKind::Streams {
                    input,
                    streams,
                    frame,
                    ..
                } => {
                    for stream in streams {
                        let (table, dir, index) = if *input {
                            (&mut self.consumers, "in", &mut inputs)
                        } else {
                            (&mut self.producers, "out", &mut outputs)
                        };
                        table.insert(
                            *stream,
                            End {
                                port: format!("{k}.{dir}[{index}]"),
                                frame: frame.is_some(),
                            },
                        );
                        *index += 1;
                    }
                }
                AiePortKind::Scalar {
                    value: ScalarBinding::Runtime(arg),
                    ..
                } => {
                    let rtp = rtp_name(
                        rtp_arg(options, &kernel.name, arg)?,
                        &kernel.name,
                        &port.name,
                    );
                    let _ = writeln!(self.members, "  adf::port<adf::input> {rtp};");
                    let _ = writeln!(
                        self.body,
                        "    adf::connect<adf::parameter>({rtp}, adf::async({k}.in[{inputs}]));"
                    );
                    inputs += 1;
                }
                AiePortKind::Scalar { .. } => {}
            }
        }
        Ok(())
    }

    fn plio(&mut self, index: usize, stream: &AieStream, input: bool, width: u32, freq: &str) {
        let p = format!("p_{}", stream.name);
        let (class, end, table) = if input {
            ("input_plio", "out", &mut self.producers)
        } else {
            ("output_plio", "in", &mut self.consumers)
        };
        let _ = writeln!(self.members, "  adf::{class} {p};");
        let _ = writeln!(
            self.body,
            "    {p} = adf::{class}::create(\"{name}\", adf::plio_{width}_bits, \
             \"data/{name}.txt\"{freq});",
            name = stream.name
        );
        table.insert(
            index,
            End {
                port: format!("{p}.{end}[0]"),
                frame: false,
            },
        );
    }

    fn connect(&mut self, index: usize, stream: &AieStream) -> Result<()> {
        let (Some(src), Some(dst)) = (self.producers.get(&index), self.consumers.get(&index))
        else {
            return Err(XilinxError::AieGraph(format!(
                "AI Engine stream `{}` lacks a producer or a consumer",
                stream.fifo
            )));
        };
        let net = format!("n_{}", stream.name);
        let frame = src.frame || dst.frame;
        let kind = if frame { "" } else { "<adf::stream>" };
        let _ = writeln!(
            self.body,
            "    adf::connect{kind} {net}({}, {});",
            src.port, dst.port
        );
        if let AieStreamKind::Net { depth_words } = stream.kind {
            if !frame && depth_words > 0 {
                let _ = writeln!(self.body, "    adf::fifo_depth({net}) = {depth_words};");
            }
        }
        Ok(())
    }
}

fn graph(partition: &AiePartition, options: &GraphOptions) -> Result<String> {
    let mut text = GraphText::default();
    for kernel in &partition.kernels {
        text.kernel(kernel, options)?;
    }
    let freq = options
        .plio_mhz
        .map(|mhz| format!(", {mhz}"))
        .unwrap_or_default();
    for (index, stream) in partition.streams.iter().enumerate() {
        if let AieStreamKind::Plio { input, width } = stream.kind {
            text.plio(index, stream, input, width, &freq);
        }
    }
    for (index, stream) in partition.streams.iter().enumerate() {
        text.connect(index, stream)?;
    }
    let mut out = format!(
        "// Generated by TAPA: the AI Engine graph of this design.\n\
         #include <adf.h>\n\n#include \"kernels.h\"\n\n\
         class TapaAieGraph : public adf::graph {{\n public:\n{members}\n  \
         TapaAieGraph() {{\n{body}  }}\n}};\n\nTapaAieGraph {graph};\n",
        members = text.members,
        body = text.body,
        graph = graph_instance(partition.run_forever),
    );
    // `aiecompiler --target=hw` builds a simulation model of the PS side
    // too, which needs an entry point even when only `libadf.a` is wanted.
    let graph = graph_instance(partition.run_forever);
    match &options.sim {
        Some(sim) => out.push_str(&sim_main(partition, options, sim)?),
        None => {
            let _ = write!(
                out,
                "\n#if defined(__AIESIM__) || defined(__X86SIM__)\n\
                 // `tapa aiesim` builds the graph with its own entry point.\n\
                 int main() {{\n  {graph}.init();\n  {graph}.end();\n  \
                 return 0;\n}}\n#endif\n"
            );
        }
    }
    Ok(out)
}

fn sim_main(partition: &AiePartition, options: &GraphOptions, sim: &SimMain) -> Result<String> {
    let graph = graph_instance(partition.run_forever);
    let mut out = format!(
        "\n#if defined(__AIESIM__) || defined(__X86SIM__)\nint main() {{\n  \
         {graph}.init();\n"
    );
    for kernel in &partition.kernels {
        for port in &kernel.ports {
            if let AiePortKind::Scalar {
                ctype,
                width,
                value: ScalarBinding::Runtime(arg),
            } = &port.kind
            {
                let value = sim.args.get(arg).ok_or_else(|| {
                    XilinxError::AieGraph(format!(
                        "the AI Engine kernel `{}` reads the top argument `{arg}`; give its \
                         value",
                        kernel.name
                    ))
                })?;
                let _ = writeln!(
                    out,
                    "  {graph}.update({graph}.{}, static_cast<{}>({value}));",
                    rtp_name(
                        rtp_arg(options, &kernel.name, arg)?,
                        &kernel.name,
                        &port.name
                    ),
                    rtp_type(ctype, *width)?
                );
            }
        }
    }
    // ADF's `run(0)` runs zero iterations; `run()` runs until `end()`.
    if partition.run_forever {
        let _ = writeln!(out, "  {graph}.run();\n  {graph}.wait({});", sim.cycles);
    } else {
        let _ = writeln!(out, "  {graph}.run(1);");
    }
    let _ = writeln!(out, "  {graph}.end();\n  return 0;\n}}\n#endif");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    use tapa_ir::{AieKernelPort, WireValue};

    fn streams(input: bool, streams: Vec<usize>, frame: Option<u32>) -> AiePortKind {
        AiePortKind::Streams {
            input,
            plural: streams.len() > 1,
            streams,
            words: 4,
            frame,
        }
    }

    fn port(name: &str, kind: AiePortKind) -> AieKernelPort {
        AieKernelPort {
            name: name.into(),
            kind,
        }
    }

    /// PL → `Fan` (a frame in, two channels out) → `Join` (runtime `n`,
    /// constant `k`) → PL; `Join` is pinned.
    fn partition() -> AiePartition {
        let plio = |name: &str, input| AieStream {
            name: name.into(),
            fifo: name.into(),
            words: 4,
            frame: None,
            kind: AieStreamKind::Plio { input, width: 128 },
        };
        let net = |name: &str| AieStream {
            name: name.into(),
            fifo: name.into(),
            words: 4,
            frame: None,
            kind: AieStreamKind::Net { depth_words: 32 },
        };
        AiePartition {
            kernels: vec![
                AieKernel {
                    name: "Fan_0".into(),
                    task: "Fan".into(),
                    call: "Fan".into(),
                    ports: vec![
                        port("in", streams(true, vec![0], Some(64))),
                        port("out", streams(false, vec![1, 2], None)),
                    ],
                    location: None,
                    stack_bytes: None,
                    ordered: false,
                },
                AieKernel {
                    name: "Join_0".into(),
                    task: "Join".into(),
                    call: "Join<2>".into(),
                    ports: vec![
                        port("in", streams(true, vec![1, 2], None)),
                        port("c", streams(false, vec![3], None)),
                        port(
                            "n",
                            AiePortKind::Scalar {
                                ctype: "uint64_t".into(),
                                width: 64,
                                value: ScalarBinding::Runtime("n".into()),
                            },
                        ),
                        port(
                            "k",
                            AiePortKind::Scalar {
                                ctype: "int".into(),
                                width: 32,
                                value: ScalarBinding::Constant(WireValue {
                                    width: 32,
                                    value: 3,
                                }),
                            },
                        ),
                    ],
                    location: Some((10, 1)),
                    stack_bytes: Some(100),
                    ordered: true,
                },
            ],
            streams: vec![
                plio("a_q", true),
                net("fan"),
                net("fan_1"),
                plio("c_q", false),
            ],
            run_forever: false,
        }
    }

    fn render(sim: Option<SimMain>) -> BTreeMap<String, String> {
        let source = |task: &str| KernelSource {
            tu: "design.cpp".into(),
            defines: vec![format!("TAPA_TASK_DEF_{task}")],
        };
        let options = GraphOptions {
            sources: BTreeMap::from([
                ("Fan".into(), source("Fan")),
                ("Join".into(), source("Join")),
            ]),
            rtp_args: BTreeMap::from([("n".into(), 3)]),
            plio_mhz: Some(312.5),
            sim,
        };
        render_graph(&partition(), &options).expect("render")
    }

    #[test]
    fn kernels_take_word_ports_and_call_the_task() {
        let files = render(None);
        assert_eq!(
            files["kernels/Join_0.cc"],
            "// Generated by TAPA: AI Engine kernel `Join_0` of task `Join`.\n\
             #define TAPA_TASK_DEF_Join\n\
             #define TAPA_AIE_ORDERED_STREAMS\n\
             #include \"design.cpp\"\n\n\
             void tapa_aie_Join_0(input_stream<int32>* in_0, input_stream<int32>* in_1, \
             output_stream<int32>* c, uint64 n) {\n  \
             tapa::aie::invoke(Join<2>, tapa::aie::pack(in_0, in_1), c, n, \
             tapa::aie::bits{0x3ULL});\n}\n"
        );
        assert!(files["kernels.h"].contains(
            "void tapa_aie_Fan_0(tapa::aie::input_frame<int32, 256>& in, \
             output_stream<int32>* out_0, output_stream<int32>* out_1);"
        ));
    }

    #[test]
    fn graph_numbers_ports_per_direction_and_wires_every_stream() {
        let graph = &render(None)["graph.cpp"];
        for line in [
            "p_a_q = adf::input_plio::create(\"a_q\", adf::plio_128_bits, \"data/a_q.txt\", \
             312.5);",
            "adf::connect n_a_q(p_a_q.out[0], k_Fan_0.in[0]);",
            "adf::connect<adf::stream> n_fan_1(k_Fan_0.out[1], k_Join_0.in[1]);",
            "adf::fifo_depth(n_fan_1) = 32;",
            "adf::connect<adf::parameter>(rtp_3_Join_0_n, adf::async(k_Join_0.in[2]));",
            "adf::connect<adf::stream> n_c_q(k_Join_0.out[0], p_c_q.in[0]);",
            "adf::location<adf::kernel>(k_Join_0) = adf::tile(10, 1);",
            "adf::stack_size(k_Join_0) = 1136;",
            "TapaAieGraph tapa_aie;",
        ] {
            assert!(graph.contains(line), "missing `{line}` in:\n{graph}");
        }
        assert!(
            graph.contains("int main() {\n  tapa_aie.init();\n  tapa_aie.end();"),
            "a bare entry point for the hardware build's PS model"
        );
        assert!(
            !graph.contains("fifo_depth(n_a_q)"),
            "a PLIO takes no depth"
        );
    }

    #[test]
    fn simulator_main_writes_every_runtime_parameter() {
        let sim = SimMain {
            args: BTreeMap::from([("n".into(), "1000".into())]),
            cycles: 0,
        };
        let graph = &render(Some(sim))["graph.cpp"];
        assert!(graph.contains(
            "  tapa_aie.update(tapa_aie.rtp_3_Join_0_n, static_cast<uint64>(1000));\n  \
             tapa_aie.run(1);\n  tapa_aie.end();"
        ));
        let err = render_graph(
            &partition(),
            &GraphOptions {
                sim: Some(SimMain::default()),
                ..GraphOptions::default()
            },
        )
        .expect_err("no source and no argument");
        assert!(err.to_string().contains("no translation unit"), "{err}");
    }
}
